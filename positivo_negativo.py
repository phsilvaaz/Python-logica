#o código abaixo pede ao usuaro um número.
numero = int(input("Diga um número: "))
#o código abaixo verifica se o número digitado é positivo.
if numero > 0:
    print(f"O número {numero} é positivo.")
#o código abaxio verifica se o número é negativo.
else:
    print(f"O número {numero} não é positivo.")
#se (if) o número for maior que 0, é positivo. Caso o contrário (else), número negativo.

#digitando um número para ser negativo deve utilizar o sinal de subtração que é: "-" este sinal exibido.